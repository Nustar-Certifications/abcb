						<ul>
                        <li style="line-height:22px; text-align:justify;"><strong> A) </strong>&nbsp;	AB-CB reviews application from CAB for accreditation process with relevant documentation such as legal legislation etc.<br> <br>


<strong> B) </strong> AB-CB reviews documentation of applicant CAB as per the requirement of accreditation standard including quality documents, records and interview with personnel, demonstrations of assessment, certification scheme & reports of assessor's findings & share reports with applicant CAB. If there is any deficiency in documentation applicant CAB provides Corrective action plan.<br> <br>

<strong> C) </strong>	AB-CB conducts on site assessment. The assessor initially review the submitted documents, process including work place assessment & site visit on the agreed date & submit report to AB-CB accreditation committee . The scope and duration of the assessment will depend on the size of the CAB & applied scope of certification.<br> <br>

<strong> D) </strong>    AB-CB accreditation committee review the report and makes a decision regarding   accreditation. Members of this committee are individuals who have expertise in the scope of accreditation.<br> <br>

<strong> E) </strong>&nbsp;AB-CB Issue notification on successful completion of the accreditation process & issue the accreditation certificate. AB-CB provides the attestation that the assessment services of CAB conform to the relevant standards & the technical competence of these bodies. If accreditation is not granted, the applicant CAB is advised to improve the system & further application may be considered at a later date.<br> <br>

<strong> F) </strong>	Once an applicant CAB is accredited, AB-CB conducts surveillance audits at fixed intervals depending on whether the organisation is a laboratory, an IB or a CAB with visits are made to the CAB’s offices to assess the CAB’s on going compliance with the accreditation criteria. re accreditation is due after every five years.<br> <br>

